              พิมพ์ต่อกันหลายพยางค์ในช่องเดียวก็ได้ แล้ว<strong>เคาะเว้นวรรค (space)</strong> ตรงไหน ระบบจะ<strong>ตัดพยางค์ตรงนั้น</strong> —
              ส่วนหน้าอยู่โน้ตนี้ ส่วนหลังไหลไปโน้ตถัดไป แล้วเลื่อนตามให้เอง (กด <strong>Enter</strong> = ไปช่องถัดไปเฉย ๆ)
              <br /><span class="muted">พิมพ์ทั้งวรรครวดเดียวแล้วเคาะเว้นวรรคไล่ตัดทีละโน้ตได้ · จะไม่ทับคำที่โน้ตถัดไปมีอยู่แล้ว</span></li>
            <li><strong>เดินด้วยคีย์บอร์ดล้วน</strong> (ไม่ต้องใช้เมาส์) — ลูกศรไปตามทิศจริงบนจอ:
              <strong>← →</strong> ซ้าย-ขวาในแถวเดียวกัน (โน้ต→โน้ต หรือ คำ→คำ) ·
              <strong>↓</strong> จากโน้ตลงไปคำของมัน / จากคำลงไปโน้ตบรรทัดถัดไป ·
              <strong>↑</strong> จากคำขึ้นไปโน้ตของมัน / จากโน้ตขึ้นไปคำบรรทัดก่อน ·
              <strong>Ctrl+← →</strong> ข้ามทีละห้อง · <strong>Ctrl+↑ ↓</strong> ข้ามทีละบรรทัด
              <br /><span class="muted">บนมือถือใช้ปุ่ม <strong>◀ ▶</strong> ในแถบล่างไล่ทีละหน่วย (โน้ต→คำ→โน้ต…)</span></li>
            <li><strong>ย้อน / ทำซ้ำ</strong> — พิมพ์ผิดกดย้อนได้เสมอ: ปุ่ม <strong>ย้อน</strong> กับ <strong>ทำซ้ำ</strong>
              อยู่ซ้ายสุดของแถบ (คีย์ลัด <code>Ctrl+Z</code> · <code>Ctrl+Y</code> หรือ <code>Ctrl+Shift+Z</code>) ·
              ย้อนได้ทุกอย่างที่แก้ในโหมดนี้ — โน้ต · เนื้อร้อง · คอร์ด · สัญลักษณ์ · แทรก/ลบ ·
              ถ้ายังไม่มีอะไรให้ย้อน ปุ่มจะจางและกดไม่ได้ (ไม่ใช่กดแล้วเงียบ)</li>
            <li><strong>ไม่ต้องหาปุ่มเอง</strong> — ในโหมดแก้มี<strong>แถวปุ่มสัญลักษณ์</strong>ครบทุกตัว
              แบ่งเป็น 3 กลุ่ม (ความยาว · เสียง · กลุ่ม/ห้อง) · ปุ่มแต่ละอันบอก<strong>อักขระที่จะได้</strong>
              กับ<strong>ชื่อไทย</strong>ติดอยู่บนปุ่มตลอด · พอพิมพ์อักขระนั้นจากคีย์บอร์ดได้สำเร็จครั้งหนึ่ง
              ปุ่มจะ<strong>จำตำแหน่งปุ่มจริงบนแป้นพิมพ์ของเครื่องนั้น</strong>มาแสดงด้วย (เช่น <code>^</code> ขึ้นว่า ⇧ + 6)
              — ครั้งต่อไปพิมพ์เองได้เลยไม่ต้องกดปุ่ม</li>
            <li><strong>สัญลักษณ์จังหวะ พิมพ์บนแผ่นได้เลย</strong> (คอมพิวเตอร์) ·
              <strong>กดซ้ำ = เอาออก</strong> ทุกตัว (ใส่/ลบด้วยปุ่มเดียว) —
              <code>_</code> เขบ็ต (กดซ้ำ = 1 ชั้น → 2 ชั้น → ไม่มี) ·
              <code>.</code> จุดเพิ่มความยาว (กดซ้ำ = 1 จุด → 2 จุด → ไม่มี) ·
              <code>^</code> ยืดเสียง (fermata) ·
              <code>-</code> ลากเสียงอีกหนึ่งจังหวะ · <code>{ }</code> สามพยางค์ ·
              <code>|</code> เส้นกั้นห้อง (กดซ้ำที่โน้ตท้ายห้อง = รวมห้องคืน) ·
              <code>#</code> ชาร์ป · <code>b</code> แฟลต · <code>n</code> เนเชอรัล (สามตัวนี้กลุ่มเดียวกัน)
              <br /><strong>ระดับเสียง (octave):</strong> ปุ่ม <strong>สูง↑ / ต่ำ↓</strong> หรือคีย์บอร์ด —
              <code>'</code> <em>หลัง</em>เลข = เสียง<strong>สูง</strong> (เช่น <code>5'</code>) ·
              <code>,</code> = เสียง<strong>ต่ำ</strong> (ได้ <code>.5</code> จุดอยู่ใต้เลข) · จะพิมพ์ <code>.</code> <em>ก่อน</em>เลขก็ได้เหมือนกัน —
              ถ้ากด <code>.</code> แล้วไม่ตามด้วยเลข จะเป็น<strong>จุดเพิ่มความยาว</strong>แทน · จุดไปอยู่บน/ล่างเลขให้เองอัตโนมัติ
              <br /><span class="muted">พิมพ์สลับลำดับได้ ระบบจัดเรียงให้เองตามมาตรฐาน</span></li>
            <li><strong>โยงเสียง <code>~</code> กับ เอื้อน <code>( )</code> ต่างกันตรงนี้</strong> —
              <code>~</code> <strong>โยงเสียง (tie):</strong> แตะโน้ต แล้วกด <code>~</code> เพื่อ<strong>โยงกับโน้ต
              เสียงเดียวกันที่อยู่ติดกัน</strong> ให้เป็นเสียงเดียวลากยาว (ไม่ดีดซ้ำ · ต้องเป็นตัวเลขเดียวกันเท่านั้น) ·
              กดอีกครั้ง = เลิกโยง · <code>( )</code> <strong>เอื้อน (slur):</strong> คลุมโน้ต<strong>ต่างเสียง</strong>
              หลายตัวที่ร้องด้วย<strong>คำเดียว</strong> (พิมพ์ <code>(</code> หน้ากลุ่ม แล้ว <code>)</code> ท้ายกลุ่ม)
              <br /><span class="muted">สรุป: เสียงเดียวกันลากต่อ → <code>~</code> · คำเดียวหลายเสียง → <code>( )</code></span></li>
            <li><strong>เล่นซ้ำ และ "จบรอบ 1. / 2."</strong> — ที่แถบบนของโหมดแก้:
              ปุ่ม <strong>เล่นซ้ำ</strong> (<code>‖: :‖</code>) คลุมบรรทัดที่กำลังแก้ให้เล่นสองเที่ยว ·
              ปุ่ม <strong>จบรอบ</strong> ข้าง ๆ กัน ทำให้บรรทัดนั้นเป็น<strong>ห้องจบ</strong> — กดหนึ่งครั้ง = จบรอบ 1
              (เล่นเฉพาะเที่ยวแรก) · กดอีกครั้ง = จบรอบ 2 (เล่นเฉพาะเที่ยวซ้ำ) · กดอีกครั้ง = เอาออก
              <br /><span class="muted">อยากให้จบรอบเป็นราย<strong>ห้อง</strong> (บรรทัดเดียวมีทั้ง 1. และ 2.)
              แตะโน้ตในห้องนั้น → ปุ่ม <strong>⋯</strong> → ช่อง "ห้องจบ" · แผ่นเพลงจะพิมพ์เลข 1. / 2. ให้
              และตอนกดฟัง เสียงจะเล่นตามลำดับจริง</span></li>
            <li><strong>ให้บางข้อวนไม่เหมือนกัน</strong> — ทำนองเดียวใช้ได้หลายข้อ แต่ถ้า
              <strong>บางข้อวนต่างจากข้ออื่น</strong> (เช่นข้อ 1 ร้องซ้ำท่อน แต่ข้อ 2-3 ร้องผ่านครั้งเดียว)
              ไม่ต้องคัดลอกทำนอง — เปิดข้อนั้นแล้วกด <strong>"การวนซ้ำของข้อนี้"</strong> ใต้หัวข้อ ตั้งได้:
              <br /><span class="muted"><strong>ข้อนี้ไม่วนซ้ำ</strong> (ร้องผ่านครั้งเดียว) ·
              <strong>เล่นซ้ำกี่รอบ</strong> (เฉพาะข้อนี้) · <strong>เข้าห้องจบชุดที่ N</strong> ·
              <strong>ไม่ต้องร้องรับหลังข้อนี้</strong> — ข้อที่ไม่ตั้งอะไรจะวนตามทำนองปกติ ·
              ถ้าเผลอลบเครื่องหมายที่ข้ออื่นอ้างถึง ระบบจะเตือนและร้องตามทำนองแทน ไม่เล่นมั่ว</span></li>
            <li><strong>ใส่จุดวนร้อง / นำทาง (D.C. · D.S. · โคดา · Fine)</strong> — สำหรับเพลงที่ต้อง
              <strong>ย้อนกลับไปเล่นซ้ำ</strong>ตอนจบ: กดปุ่ม <strong>วน/นำทาง</strong> บนแถบบนของโหมดแก้
              (หรือคีย์ลัด <code>Ctrl+K</code>) แล้วเลือก<strong>รูปแบบสำเร็จเป็นภาษาไทย</strong> เช่น
              “ย้อนต้นเพลง (D.C.)” · “ย้อน 𝄋 แล้วข้ามไปโคดา (D.S. al Coda)” — ไม่ต้องรู้ทฤษฎี
              <br /><span class="muted"><strong>วิธีใช้:</strong> แตะโน้ตตรง<strong>จุดที่จะให้ย้อน</strong>ก่อน
              → เลือกรูปแบบ → ระบบจะขึ้น<strong>ชิปบอกจุดที่ยังต้องวาง</strong> (เช่น 𝄋 เครื่องหมายวน · 𝄌 โคดา)
              แตะชิปแล้ว<strong>แตะโน้ตปลายทาง</strong> ระบบผูกให้เองอัตโนมัติ · วางไม่ครบจะมี<strong>แถบเตือน</strong>จนกว่าจะครบ ·
              มีแถบ <strong>“ลำดับเล่นจริง”</strong> โชว์ว่าจะเล่นเรียงยังไงก่อนกดฟัง · แตะรายการสัญลักษณ์เพื่อ<strong>แก้/ลบ</strong>ได้
              (ลบคำสั่งที่มีชุดจะถามว่าลบจุดที่มันชี้ไปด้วยไหม)</span></li>
            <li><strong>ฟังได้ทันทีโดยไม่ต้องออกจากโหมดแก้</strong> — บนแถบบนสุดของโหมดแก้มีปุ่มฟัง 4 ปุ่ม:
              <strong>ทั้งเพลง</strong> · <strong>ท่อนนี้</strong> (เฉพาะท่อนที่เคอร์เซอร์อยู่) ·
              <strong>บรรทัดนี้</strong> (เฉพาะบรรทัดที่กำลังแก้) ·
              <strong>ห้องนี้</strong> (เฉพาะห้องที่เคอร์เซอร์อยู่ — ละเอียดที่สุด แก้โน้ตตัวเดียวแล้วฟังเช็คทันที
              ไม่ต้องฟังทั้งบรรทัด) · กดปุ่มที่กำลังเล่นอยู่อีกครั้ง = หยุด
              <br /><span class="muted">คีย์ลัด: <code>Ctrl+Enter</code> ฟังบรรทัดนี้ ·
              <code>Ctrl+Shift+Enter</code> ฟังท่อนนี้ · <code>Esc</code> หยุด ·
              ระหว่างเล่นจะมีข้อความบอกว่า<strong>กำลังเล่นอะไรอยู่</strong> และคำที่ร้องถึงจะไฮไลต์ตามเหมือนโหมดฝึกร้อง ·
              เสียง เครื่องดนตรี คีย์ ความเร็ว และการวนซ้ำรายข้อ <strong>เหมือนกับตอนกดฟังปกติทุกอย่าง</strong></span></li>
            <li><strong>⚙ ตั้งค่าเพลง — เลขเพลง ชื่อ คีย์ จังหวะ ความเร็ว ธีม หมวด</strong> อยู่ในโหมดแก้แล้ว
              (ปุ่ม <strong>⚙ ตั้งค่าเพลง</strong> บนแถบบนสุด · ไม่ต้องออกไปหน้าแก้ไขแบบเก่าอีก) ·
              จอใหญ่แผงจะกางอยู่ข้าง ๆ แผ่นเพลง (เห็นผลทันทีที่เปลี่ยน) · มือถือเปิดเป็นหน้าเต็มจอ กด ✕ กลับ
              <br /><span class="muted"><strong>เปลี่ยนคีย์ = ย้ายทั้งเพลง</strong> — โน้ตตัวเลขเท่าเดิม
              (เลขคือขั้นของคีย์) ส่วน<strong>คอร์ดขยับตามคีย์ใหม่ให้เอง</strong> และเสียงที่กดฟังจะสูง-ต่ำตามคีย์นั้นจริง ·
              ทุกช่องเก็บพร้อมเพลงตอนกดบันทึก ไม่มีปุ่มตกลงแยก — ดูสถานะที่แถบเดียวกัน</span></li>
            <li><strong>🎼 โครงเพลง — จัดลำดับท่อน · เลือก/แยกทำนอง · คัดลอก/วาง</strong> อยู่ในโหมดแก้แล้ว
              (ปุ่ม <strong>โครงเพลง</strong> บนแถบบนสุด ข้าง ๆ ตั้งค่าเพลง · ไม่ต้องออกไปหน้าแก้ไขแบบเก่าอีก) ·
              จอใหญ่แผงกางข้างแผ่นเพลง · มือถือเปิดเต็มจอ กด ✕ กลับ
              <ul>
                <li><strong>ลำดับท่อน (ข้อ 1 · รับ · ข้อ 2…)</strong> — <strong>ลากการ์ด</strong>หรือปุ่ม <strong>▲ ▼</strong>
                  จัดลำดับ · <strong>+ เพิ่มท่อน</strong> (ทำนองเดียวกับท่อนก่อน) · <strong>ทำซ้ำท่อน</strong> (เนื้อ+ทำนองเดิม) ·
                  <strong>ลบท่อน</strong> · ติ๊ก <strong>"รับทุกข้อ"</strong> เพื่อให้ท่อนนั้นเป็นท่อนรับที่ร้องหลังทุกข้อ</li>
                <li><strong>ทำนองของแต่ละท่อน (♫A / ♫B)</strong> — แต่ละการ์ดเลือกได้ว่าใช้ทำนองไหน ·
                  ท่อนที่<strong>ใช้ทำนองเดียวกัน</strong> จะเรืองแสงพร้อมกันเมื่อชี้ (เห็นว่าการแก้กระทบท่อนไหนบ้าง) ·
                  อยากให้ท่อนหนึ่ง<strong>ทำนองต่างจากท่อนอื่นที่แชร์กันอยู่</strong> กด <strong>"แยกทำนอง"</strong>
                  จะได้ทำนองสำเนาของตัวเอง (♫ ตัวใหม่) แก้ได้โดยไม่กระทบท่อนอื่น
                  <br />เพลงที่มี<strong>หลายทำนอง (♫A · ♫B…)</strong> — ในหัวข้อ <strong>"ทำนอง"</strong> <strong>แตะแถบทำนองที่ต้องการ</strong>
                  เพื่อสลับดู/แก้โครงของทำนองนั้น · แถบที่กำลังทำงานขึ้นป้าย <strong>● กำลังแก้</strong> ไม่ต้องเดาว่าอยู่ทำนองไหน</li>
                <li><strong>คัดลอก / วาง / จัดลำดับ ห้อง–บรรทัด</strong> — ใต้หัวข้อ "คัดลอก / วาง · จัดลำดับ" มี
                  <strong>โครงทำนอง</strong>ของทำนองที่เลือก มี<strong>หัวข้อ ♫ บอกชื่อทำนอง</strong> และ<strong>บรรทัดนำทาง</strong>
                  ("กำลังแก้: ♫A › ข้อ 1 › บรรทัด 1 · ห้อง 1") · ถ้ากำลังดูคนละทำนองกับเคอร์เซอร์ มีปุ่ม <strong>"ไปที่เคอร์เซอร์"</strong> พากลับ ·
                  แสดงทุกบรรทัด (แตะบรรทัดเพื่อกางดูห้องข้างใน) ·
                  <strong>คัดลอกห้อง / คัดลอกบรรทัด</strong> (จากปุ่มด้านบน หรือจากปุ่ม 📋 บนบรรทัด/ห้องนั้น) →
                  ระบบจะ<strong>โชว์จุด ▸ “วางที่นี่”</strong> ทุกช่องที่วางได้ <strong>แตะจุดที่ต้องการ</strong> เพลงจะวางตรงนั้นพอดี
                  (เห็นก่อนว่าจะลงตรงไหน ไม่ใช่ต่อท้ายอย่างเดียว)
                  <br /><strong>จัดลำดับ</strong> — <strong>ลากจับ ⁞</strong> ที่บรรทัด/ห้องไปวางตำแหน่งใหม่ในครั้งเดียว
                  หรือใช้ปุ่ม <strong>▲▼</strong> (บรรทัด) / <strong>◀▶</strong> (ห้อง) · ยังมี <strong>วางเป็นท่อนใหม่</strong> และ <strong>ทำซ้ำ</strong> เหมือนเดิม
                  <br /><strong>ลบบรรทัด</strong> — ปุ่ม <strong>🗑</strong> ท้ายบรรทัด ลบทั้งบรรทัด (โน้ต+เนื้อของบรรทัดนั้น) ทันที ·
                  เผลอลบก็กด <strong>ย้อน (Ctrl+Z)</strong> คืนได้ครบ · ทำนองต้องเหลืออย่างน้อย 1 บรรทัด (บรรทัดสุดท้ายลบไม่ได้)
                  <br /><span class="muted">วาง = ก๊อปเฉพาะ<strong>ทำนอง</strong> (โน้ต+คอร์ด) ไม่พาเนื้อร้องข้ามท่อน · คำร้องเดิมของท่อน
                  ยังตรงกับโน้ตเสมอ (ระบบเว้นช่องคำให้ตรงจุดที่แทรก) ·
                  ถ้าห้อง/บรรทัดที่ก๊อปมีเครื่องหมายเล่นซ้ำ ระบบจะ<strong>สร้างรหัสใหม่ให้เอง</strong> ไม่ให้ชนกับของเดิม
                  (การวนซ้ำจึงไม่เพี้ยน)</span></li>
              </ul></li>
            <li><strong>ชุดเนื้อร้อง — เพิ่ม/ลบ เนื้อหลายชุดบนทำนองเดิม</strong> พออยู่ในโหมดแก้
              <strong>แถบชุดเนื้อร้องจะกางค้างไว้</strong> (ไม่ยุบ) จะได้รู้ตลอดว่ากำลังพิมพ์อยู่ชุดไหน
              <ul>
                <li><strong>＋ เพิ่มชุด</strong> — สร้าง<strong>เนื้อร้องชุดใหม่บนทำนองเดิม</strong> (โน้ต/คอร์ดใช้ร่วมกันทุกชุด
                  ไม่ต้องพิมพ์ใหม่) แล้วพาไปที่ชุดที่เพิ่งสร้างให้เลย · เพลงธรรมดาที่ยังมีชุดเดียว
                  จะเห็นปุ่ม <strong>＋ เพิ่มชุดเนื้อร้อง</strong> เบา ๆ อยู่เหนือแผ่นเพลง</li>
                <li><strong>🗑 ลบชุดนี้</strong> — ลบ<strong>เฉพาะเนื้อร้องของชุดที่เลือกอยู่</strong> ·
                  ระบบ<strong>ถามยืนยันก่อนเสมอ</strong> โดยบอกชื่อชุดที่จะลบ (กด <strong>Esc</strong> หรือ
                  <strong>ยกเลิก</strong> เพื่อไม่ลบ) · <strong>ทำนองไม่หาย</strong> และท่อนที่ใช้ร่วมกันทุกชุด
                  (เช่นท่อนรับ) ก็ยังอยู่ครบ
                  <br /><strong>เลขชุดเรียงใหม่ให้เอง</strong> — ลบชุดที่ 2 จาก 3 ชุด ที่เหลือจะกลายเป็น
                  <span class="verified-eg">เนื้อร้องที่ 1</span> <span class="verified-eg">เนื้อร้องที่ 2</span>
                  ไม่ใช่ 1 กับ 3 · <strong>ลบจนเหลือชุดเดียว</strong> เพลงจะกลับเป็นเพลงธรรมดา (แถบชุดหายไป) ·
                  <strong>ชุดสุดท้ายลบไม่ได้</strong> เพราะเพลงต้องมีเนื้ออย่างน้อย 1 ชุด
                  <br /><span class="muted">ลบแล้วยัง<strong>ไม่ถูกบันทึกจนกว่าจะกดบันทึก/จบงาน</strong> ·
                  ถ้าเคยส่งลิงก์ของชุดที่ลบไปให้ใคร ลิงก์นั้นจะยังเปิดเพลงได้ แต่จะขึ้นบอกผู้เปิดว่าชุดนั้นถูกลบแล้ว</span></li>
              </ul></li>
            <li><strong>รู้ตลอดว่างานอยู่ขั้นไหน + จบงานยังไง</strong> — โหมดแก้มี<strong>แถบสถานะ</strong>บนสุด
              บอกลำดับ <strong>แก้ → ร่าง → รอตรวจ → เผยแพร่แล้ว</strong> ไฮไลต์ว่าตอนนี้อยู่ขั้นไหน พร้อมบอก<strong>ขั้นต่อไป</strong> ·
              ระบบ<strong>เก็บร่างให้อัตโนมัติ</strong> (ไม่ต้องคอยกดเซฟ งานไม่หาย) · ปุ่ม<strong>จบงานหลักปุ่มเดียว</strong>ที่เปลี่ยนป้ายตามสิทธิ์:
              <ul>
                <li><strong>ทีมงานทั่วไป</strong> → <strong>"ส่งตรวจ"</strong> (ส่งให้ผู้ดูแลตรวจแล้วนำขึ้นคลัง) ·
                  ระหว่างรอยัง <strong>"ถอนกลับมาแก้"</strong> ได้ · ถ้าถูกส่งกลับจะเห็น<strong>หมายเหตุ</strong>ค้างบนแถบ ให้แก้แล้วส่งใหม่</li>
                <li><strong>ผู้ดูแล (approver)</strong> → <strong>"เผยแพร่"</strong> ขึ้นคลังทันที</li>
                <li><strong>ยังไม่ได้เข้าสู่ระบบ</strong> → <strong>"ส่งให้ทีม"</strong> — ดาวน์โหลดไฟล์เพลง (JSON) แล้วแนบส่งอีเมลให้ทีมนำขึ้นให้
                  (ไม่ต้องมีบัญชี) · หรือเข้าสู่ระบบเพื่อส่งตรวจในเว็บ · ปุ่ม <strong>ดาวน์โหลด JSON</strong> เก็บไฟล์ไว้แก้ต่อได้ด้วย <strong>⋮ → เปิดไฟล์ JSON</strong></li>
              </ul>
              ปุ่ม <strong>"เสร็จ"</strong> = แค่ออกจากโหมดแก้กลับหน้าฝึกร้อง <em>ไม่ได้</em>ส่งหรือเผยแพร่ ·
              ถ้าเผลอปิดหรือรีเฟรช เว็บจะถามให้<strong>กู้คืนงานที่ค้างไว้</strong>ตอนเปิดเพลงนั้นอีกครั้ง</li>
          </ul>
          เนื้อร้องทุกข้อที่ใช้ทำนองเดียวกันจะขยับตามให้เอง คำไม่เหลื่อม · <strong>คอร์ด — ใส่ตรงโน้ตเลย:</strong>
          <strong>คลิก/แตะช่องเหนือโน้ต</strong> (โน้ตที่เลือกอยู่ถ้ายังไม่มีคอร์ดจะมีเครื่องหมาย <code>＋</code> จาง ๆ บอกว่ากดใส่คอร์ดได้)
          หรืออยู่ที่โน้ตแล้ว<strong>กด <code>C</code></strong> — ช่องพิมพ์คอร์ดจะเด้งขึ้น<strong>เหนือโน้ตนั้น</strong>
          ระหว่างพิมพ์มีตัวอย่างคอร์ดโชว์ให้เห็นว่าอ่านออกไหม · แล้ว
          <strong>กด <code>Space</code> (หรือ <code>Tab</code>) = ยืนยันแล้วไปโน้ตถัดไปทันที</strong>
          — ใส่คอร์ดรัวทั้งเพลงด้วยคีย์บอร์ดได้ไม่ต้องแตะเมาส์ (ปุ่ม <strong>โน้ตถัดไป</strong> ในช่องก็กดได้ ทำงานเหมือน Space) ·
          <code>Shift+Space</code>/<code>Shift+Tab</code> = ย้อนโน้ตก่อนหน้า ·
          <code>Enter</code> = ยืนยันแล้วปิด · <code>Esc</code> = ยกเลิก · <strong>บนมือถือ</strong> มีปุ่มคอร์ดยอดนิยมให้แตะ
          + ปุ่ม <strong>โน้ตถัดไป →</strong> · <strong>ลบคอร์ด</strong> = ลบข้อความให้ว่างแล้ว
          <code>Enter</code> หรือกดปุ่มถังขยะในป๊อปอัป · หรือใช้ปุ่ม <strong>＋ คอร์ด</strong> บนแถบก็ได้ ·
          <strong>คอร์ดไหนก็พิมพ์ได้</strong> (เช่น <code>F#m7b5</code> · <code>Cmaj7</code> · <code>Dsus4</code> · <code>G/B</code>) —
          ถ้าพิมพ์ผิดจนอ่านไม่ออก ระบบ<strong>เก็บข้อความไว้ให้</strong> (ทำเป็นสีแดงเตือน) แล้วยัง<strong>ไปโน้ตถัดไปได้ไม่สะดุด</strong> กลับมาแก้ทีหลังได้ ·
          ลบโน้ตหมดห้อง คอร์ดหายเอง · ออกจากโหมดแก้ด้วยปุ่ม <strong>✓ เสร็จ</strong> หรือกด <code>Esc</code>
          (ระหว่างแก้ แท็บ ฝึกร้อง/แผ่นเพลง/แก้ไข ด้านบนจะซ่อนไว้ให้มีสมาธิ กลับมาเมื่อกดเสร็จ)
          <br /><span class="muted"><strong>แถบเครื่องมืออยู่ล่างจอเสมอ ไม่ทับแผ่นเพลง</strong> —
          แผ่นเพลงเลื่อนอยู่ในกรอบของตัวเอง แถบเครื่องมือเกาะอยู่ใต้กรอบนั้น จึงไม่มีปุ่มไหนมาบังคำร้องที่กำลังพิมพ์
          และปุ่มอยู่ที่เดิมตลอดไม่ขยับหนี · <strong>บนคอมพิวเตอร์</strong> ใช้คีย์บอร์ดตรง ๆ: เลข <strong>1–7</strong> = โน้ต ·
          <strong>#</strong> = ชาร์ป · <strong>b</strong> = แฟลต · ปุ่ม <strong>สูง/ต่ำ</strong> · <strong>แทรก/ทับ</strong>
          และปุ่ม <strong>? วิธีใช้</strong> (รวมคีย์ลัดทั้งหมด) อยู่บนแถบนั้น — <strong>ครั้งแรกที่เข้าโหมดแก้ วิธีใช้จะเปิดให้เอง</strong>
          ครั้งต่อ ๆ ไปจะพับเก็บไว้ กดปุ่ม ? เมื่อไรก็เปิดดูได้ · <strong>บนมือถือ</strong> แตะแล้วคีย์บอร์ดเครื่องเด้งขึ้นมา
          (แป้นเลขสำหรับโน้ต · แป้นไทยสำหรับเนื้อ) แถบเครื่องมือ (ลูกศร · สูง/ต่ำ · ♯♭ · แทรก/ทับ) ขยับขึ้นมาอยู่เหนือคีย์บอร์ดให้เอง ·
          ใครก็แก้ได้ จะเก็บถาวรเข้าคลังค่อยเข้าสู่ระบบ</span></li>
        <li><strong>กดแท็บด้านบน (ฝึกร้อง · แผ่นเพลง · แก้ไข) ตอนอยู่ในโหมดแก้ = ออกจากโหมดแก้</strong> —
          <strong>ไม่มีกล่องเด้งมาถามให้รำคาญ</strong> เพราะงานที่ยังไม่บันทึกไม่หายไปไหน (เว็บเก็บสำเนาไว้ในเครื่องทุกครั้งที่พิมพ์) ·
          จะมี<strong>แถบบอกอยู่บนหน้า</strong>ว่า "ออกจากโหมดแก้แล้ว · งานยังอยู่ครบ" พร้อมปุ่ม <strong>กลับไปแก้ต่อ</strong> กดทีเดียวกลับเข้าที่เดิม
          <br /><span class="muted">ยกเว้นกรณีเดียว — ถ้าเบราว์เซอร์เก็บสำเนาให้ไม่ได้ (เช่นโหมดไม่ระบุตัวตน หรือที่เก็บเต็ม)
          เว็บจะถามก่อนออกจริง ๆ เพราะครั้งนั้นงานจะหายถ้าปิดหน้า</span></li>
        <li><strong>ดาวน์โหลด / พิมพ์</strong> — กดปุ่มลูกศรลงบนแถบเครื่องเล่น เลือกได้ 3 แบบ:
          <strong>พิมพ์ / บันทึก PDF</strong> · <strong>ข้อมูลเพลง (JSON)</strong> ·
          และ<strong>ไฟล์เสียง MP3</strong> (เสียงเปียโนจริงตามคีย์และความเร็วที่ตั้งไว้)
          <br>เลือก<strong>ขนาดกระดาษ</strong>ได้ในเมนูนี้ — A4 (ค่าเริ่มต้น) · Letter · A5 — เว็บจะจำขนาดที่เลือกไว้ และพิมพ์ออกมาตรงตามนั้น
          <br>เวลาพิมพ์ เพื่อให้แผ่นสวยเรียบร้อย ในกล่องพิมพ์ให้ <strong>ปิด "หัวกระดาษและท้ายกระดาษ" (Headers and footers)</strong> —
          เว็บใส่ชื่อเพลง ชื่อเว็บ เลขหน้า และวันที่ให้เองครบแล้ว</li>
      </ul>
      <p class="muted" style="margin-bottom: 0">
        ทุกเพลงในคลังผ่านการตรวจจากทีมงานแล้ว (ทีมงานที่เข้าสู่ระบบจะเห็นป้าย
        <span class="verified-eg"><Icon name="badge-check" :size="14" />✓ ตรวจแล้ว</span> กำกับไว้ว่าเพลงไหนตรวจเสร็จ)
      </p>

      <h3 id="howto-studio" class="howto-h"><Icon name="file-plus" :size="22" class="howto-ico" />คีย์เพลง (ห้องทำเพลง)</h3>
      <p>
        เริ่มเพลงใหม่ได้ทันทีจากปุ่ม <strong>＋ สร้างเพลงใหม่</strong> — บนคอมพิวเตอร์อยู่มุมขวาบนของแถบ
        บนมือถือเป็น<strong>ปุ่มลอยมุมขวาล่าง</strong>ของหน้ารายการเพลง (หรือเปิดจากเมนู ☰ ก็ได้) —
        กดแล้วจะเปิดแผ่นเพลงเปล่าให้คีย์ได้เลย โดยไม่ต้องเปิดเพลงเก่าก่อน
        <br>กำลังแก้เพลงอยู่แล้วอยากขึ้นเพลงใหม่? กดปุ่ม <strong>＋ เพลงใหม่</strong> ที่แถบเครื่องมือ<strong>ในตัวแก้ (✏️)</strong>
        ได้เลย — เว็บจะเปิดแผ่นเพลงเปล่าให้คีย์ต่อทันที ไม่ต้องกลับไปหน้าแรก (งานที่แก้ไว้เดิมยังเก็บกันหายไว้ให้)
      </p>
      <ul>
        <li>เพลงแบ่งเป็น <strong>บรรทัด → ห้อง → ช่อง</strong>: 1 ช่องเล็ก = โน้ต 1 ตัว = 1 คำ
          กด Enter หรือเว้นวรรคเพื่อไปช่องถัดไป กดลูกศรซ้าย-ขวาเพื่อเลื่อน
          <br /><span class="muted">ยกเว้น<strong>เอื้อน</strong> (ร้องคำเดียวหลายโน้ต): พิมพ์โน้ตติดกันในช่องเดียว
          ไม่เว้นวรรค แล้วครอบวงเล็บ เช่น <code>(65)</code> — ดู<a href="#/notation#rhythm">คู่มือทำเพลง</a></span></li>
        <li>ใช้<strong>แผงปุ่มสัญลักษณ์</strong>ที่แถบล่างจอ (เลื่อนไปไหนก็ตามไปด้วย):
          แตะช่องโน้ตก่อน แล้วจิ้มสัญลักษณ์ที่ต้องการ — ชาร์ป/แฟลต จิ้มก่อนหรือหลังพิมพ์เลขก็ได้</li>
        <li><strong>นำทางเร็วในเพลง</strong> — ที่แถบล่างจอมี<strong>ปุ่มลูกศร</strong>ให้ข้ามไปมาได้เลย:
          <strong>◀ ▶</strong> โน้ตก่อนหน้า/ถัดไป · <strong>⏮ ⏭</strong> ข้ามทั้งห้อง ·
          <strong>▲ ▼</strong> ขึ้น/ลงบรรทัด — แตะได้ทั้งที่ยังพิมพ์อยู่ ไม่ต้องปิดแป้นพิมพ์
          <br /><span class="muted">ใช้คอมพิวเตอร์ (มีคีย์บอร์ด): กด <code>Tab</code> ไปโน้ตถัดไป ·
          <code>Ctrl</code>+ลูกศร ข้ามห้อง/บรรทัด (Windows/Linux) — เครื่อง Mac ให้ใช้ <code>Tab</code>
          หรือปุ่มลูกศรบนจอแทน (Mac กันปุ่ม Ctrl+ลูกศรไว้สลับหน้าจอ)</span></li>
        <li><strong>ใส่คอร์ดแล้วกด Enter ยืนยันได้เลย</strong> — พิมพ์ชื่อคอร์ดในช่องคอร์ด
          แล้วกด <code>Enter</code> เพื่อยืนยัน หรือ <code>Esc</code> เพื่อยกเลิก (ไม่ต้องเอาเมาส์ไปคลิก)</li>
        <li>ระบบ<strong>นับจังหวะให้ทุกห้อง</strong> — ถ้าขึ้น ❌ แปลว่าโน้ตในห้องนั้นยังไม่ครบ
          หรือเกินจังหวะของเพลง (ห้องแรกของท่อนอาจไม่เต็มห้องได้ เป็นเรื่องปกติ)</li>
        <li>กด <strong>▶ ฟังบรรทัดนี้</strong> เพื่อเช็คด้วยหูว่าคีย์ถูกไหม —
          ตอนเล่น ห้องที่กำลังดังจะสว่างขึ้นและจอเลื่อนตามให้เอง</li>
        <li>พลาดตรงไหน กด <strong>↩ เลิกทำ</strong> (หรือ Ctrl+Z) ย้อนกลับได้ทีละขั้น</li>
        <li>ถ้าหนังสือตัดห้องเดียวขึ้นบรรทัดใหม่ (เช่นก่อนท่อนฮุก) ให้ติ๊ก
          <strong>⤷ ต่อห้องจากบรรทัดก่อน</strong> ที่บรรทัดใหม่ —
          ระบบจะนับจังหวะสองท่อนนั้นรวมเป็นห้องเดียวให้ถูกต้อง</li>
        <li><strong>เว็บจะเตือนถ้าเพลงนี้มีในคลังแล้ว</strong> — พอพิมพ์ชื่อเพลง ระบบเทียบกับเพลงที่มีอยู่ให้ทันที
